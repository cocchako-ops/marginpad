/* Translated versions of the two MiCA/USDT news posts for European SEO, with hreflang.
   /blog/<slug>/<lang>/  Run: node build/gen-news-mica-i18n.js */
const fs = require('fs');
const path = require('path');
const OUT = path.join(__dirname, '..', 'dist');
const GTAG = '\n<!-- Google tag (gtag.js) -->\n<script async src="https://www.googletagmanager.com/gtag/js?id=AW-18230384038"></script>\n<script>window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments);}gtag(\'js\',new Date());gtag(\'config\',\'AW-18230384038\');</script>';

const DATA = require('./data/news-mica-i18n.json');
const LANGS = Object.keys(DATA); // de, nl, fr, es, pt, sv, no, da, fi, ru, tr
const NAMES = { de: 'Deutsch', nl: 'Nederlands', fr: 'Français', es: 'Español', pt: 'Português', sv: 'Svenska', no: 'Norsk', da: 'Dansk', fi: 'Suomi', ru: 'Русский', tr: 'Türkçe' };

// two posts: English originals live at /blog/<slug>/ (generated by gen-blog.js)
const POSTS = [
  { key: 'postA', slug: 'usdt-mica-eu-2026', ctaHref: '/blog/crypto-futures-europe/' },
  { key: 'postB', slug: 'mica-stablecoins-vs-usdt', ctaHref: '/screener' },
];

function base(slug) { return 'https://marginpad.io/blog/' + slug + '/'; }

function altLinks(slug) {
  const B = base(slug);
  let h = `<link rel="alternate" hreflang="x-default" href="${B}" />\n<link rel="alternate" hreflang="en" href="${B}" />`;
  for (const l of LANGS) h += `\n<link rel="alternate" hreflang="${l}" href="${B}${l}/" />`;
  return h;
}

function switcher(slug, cur) {
  const B = base(slug);
  const items = [`<a href="${B}">English</a>`].concat(LANGS.map(l => l === cur ? `<b>${NAMES[l]}</b>` : `<a href="${B}${l}/">${NAMES[l]}</a>`));
  return `<p style="font-size:12px;color:var(--ink-faint);margin:0 0 20px;line-height:2"> ${items.join(' · ')}</p>`;
}

function page(post, lang, t) {
  const url = base(post.slug) + lang + '/';
  const ld = `<script type="application/ld+json">{"@context":"https://schema.org","@type":"Article","headline":${JSON.stringify(t.title)},"inLanguage":"${lang}","author":{"@type":"Organization","name":"MarginPad"},"publisher":{"@type":"Organization","name":"MarginPad"},"mainEntityOfPage":"${url}"}</script>`;
  return `<!DOCTYPE html>
<html lang="${lang}">
<head>${GTAG}
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<title>${t.title} — MarginPad</title>
<meta name="description" content="${t.desc.replace(/"/g, '&quot;')}" />
<link rel="canonical" href="${url}" />
<meta name="robots" content="index, follow, max-image-preview:large" />
<meta name="theme-color" content="#0a0b0d" />
<meta property="og:title" content="${t.title.replace(/"/g, '&quot;')}" />
<meta property="og:description" content="${t.desc.replace(/"/g, '&quot;')}" />
<meta property="og:type" content="article" />
<meta property="og:url" content="${url}" />
<meta property="og:image" content="https://marginpad.io/assets/og.png" />
<link rel="icon" type="image/png" sizes="32x32" href="/assets/favicon-32.png" />
${altLinks(post.slug)}
<link rel="preconnect" href="https://fonts.googleapis.com" />
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
<link href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,600;12..96,800&family=Familjen+Grotesk:wght@400;500;600&family=Space+Mono:wght@400;700&display=swap" rel="stylesheet" />
<link rel="stylesheet" href="/assets/blog.css" />
${ld}
</head>
<body>
<div class="wrap">
  <header>
    <a class="brand" href="/">MARGIN<b style="color:#c2f64a">PAD</b></a>
    <nav class="nav"><a href="/">Calculators</a><a href="/blog/">Blog</a></nav>
  </header>
  <article>
    <h1>${t.title}</h1>
    ${switcher(post.slug, lang)}
    <p class="lead">${t.lead}</p>
    <h2>${t.h2a}</h2>
    <p>${t.pa}</p>
    <h2>${t.h2b}</h2>
    <p>${t.pb}</p>
    <h2>${t.h2c}</h2>
    <p>${t.pc}</p>
    <div class="callout"><a class="cta" href="${post.ctaHref}">${t.cta}</a></div>
  </article>
  <footer>
    <span>© 2026 MarginPad</span>
    <span><a href="/">Calculators</a> · <a href="/blog/">Blog</a> · <a href="/terms/">Terms</a> · <a href="/privacy/">Privacy</a></span>
  </footer>
</div>
</body>
</html>
`;
}

let n = 0;
for (const post of POSTS) {
  for (const l of LANGS) {
    const t = DATA[l] && DATA[l][post.key];
    if (!t) { console.log('MISSING', post.slug, l); continue; }
    const d = path.join(OUT, 'blog', post.slug, l);
    fs.mkdirSync(d, { recursive: true });
    fs.writeFileSync(path.join(d, 'index.html'), page(post, l, t));
    n++;
  }
  // inject hreflang into the English original so the cluster links both ways
  try {
    const enFile = path.join(OUT, 'blog', post.slug, 'index.html');
    let en = fs.readFileSync(enFile, 'utf8');
    en = en.replace(/\n?<link rel="alternate" hreflang="[^"]*" href="[^"]*" \/>/g, '');
    if (en.indexOf('</head>') !== -1) {
      en = en.replace('</head>', altLinks(post.slug) + '\n</head>');
      fs.writeFileSync(enFile, en);
      console.log('hreflang on English original: ' + post.slug);
    }
  } catch (e) { console.log('english hreflang skipped (' + post.slug + '):', e.message); }
}

// sitemap
try {
  const smp = path.join(OUT, 'sitemap.xml');
  let sm = fs.readFileSync(smp, 'utf8');
  const today = new Date().toISOString().slice(0, 10);
  let added = 0;
  for (const post of POSTS) {
    // ensure the English original is in the sitemap too
    const en = base(post.slug);
    if (sm.indexOf(en) === -1) { sm = sm.replace('</urlset>', `  <url><loc>${en}</loc><lastmod>${today}</lastmod><changefreq>weekly</changefreq><priority>0.8</priority></url>\n</urlset>`); added++; }
    for (const l of LANGS) {
      const loc = en + l + '/';
      if (sm.indexOf(loc) === -1) { sm = sm.replace('</urlset>', `  <url><loc>${loc}</loc><lastmod>${today}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>\n</urlset>`); added++; }
    }
  }
  if (added) { fs.writeFileSync(smp, sm); console.log('sitemap: +' + added + ' MiCA URLs'); }
} catch (e) { console.log('sitemap skipped:', e.message); }
console.log('done:', n, 'translated MiCA pages');
